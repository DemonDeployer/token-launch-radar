// Regenerate dashboard/plans.js from lib/plans.ts for the current board's top rows.
//
// plans.js is the compact form the detail drawer prefers: only the researched
// steps, as [text, cost, time] triples, for the top 25 rows. It must fit the
// dossier's 65,536-byte text budget together with app.js and app.css, so the
// blurb is NOT repeated here (data.js already carries it) and only researched
// rows are included; any other row's drawer falls back to its farm_steps.
//
// Usage (from the repo root, after a build so ranks are known):
//   node scripts/gen-plans.ts --input <snapshot.json> [--top 25]
// Then rebuild; the dossier is only correct once plans.js matches the board.
import { readFileSync, writeFileSync } from 'node:fs';
import { buildRadar, parseSnapshot } from '../lib/model.ts';
import { PLANS } from '../lib/plans.ts';

function arg(name: string, fallback: string): string {
  const at = process.argv.indexOf(`--${name}`);
  if (at >= 0 && at + 1 < process.argv.length) return process.argv[at + 1]!;
  const withEquals = process.argv.find((a) => a.startsWith(`--${name}=`));
  return withEquals === undefined ? fallback : withEquals.slice(name.length + 3);
}

const snapshot = parseSnapshot(readFileSync(arg('input', '/input/snapshot.json'), 'utf8'));
const top = Number(arg('top', '25'));
const { radar } = buildRadar(snapshot);
const rows = radar.rows.slice(0, top);
const out: Record<string, { s: [string, string, string][] }> = {};
let missing = 0;
for (const r of rows) {
  const p = PLANS[r.slug];
  if (!p) { missing++; continue; }
  out[r.slug] = { s: p.steps.map((s) => [s.text, s.cost, s.time] as [string, string, string]) };
}
const text = `// Compact researched farm plans for the board's top ${top} rows, generated by\n// scripts/gen-plans.ts from lib/plans.ts. The detail drawer prefers these steps;\n// rows without an entry fall back to their farm_steps in data.js.\nwindow.FARM_PLANS = ${JSON.stringify(out)};\n`;
writeFileSync(new URL('../dashboard/plans.js', import.meta.url), text);
process.stdout.write(
  `gen-plans: top ${top} rows, ${Object.keys(out).length} researched plans, ${missing} without a researched plan, ${Buffer.byteLength(text)} bytes\n`,
);
